-- NFR-PRF-05 bulk data for the throwaway `ulms_perf` database.
--
-- Adds >= 10,000 equipment units and >= 100,000 historical loan rows
-- (Reservations + UsageLog) via set-based generate_series inserts, so it
-- runs in seconds instead of one round trip per row. Never point this at
-- the dev database `app` - it is only safe against a scratch DB seeded
-- fresh by `npm run seed`.
--
-- Usage:
--   docker exec -i postgres psql -U postgres -d ulms_perf -f - < perf/seed-large-dataset.sql
-- or, from a shell with psql installed:
--   psql "postgresql://postgres:postgres@localhost:5432/ulms_perf" -f perf/seed-large-dataset.sql

\set ON_ERROR_STOP on
BEGIN;

-- One ConditionLog row every bulk UsageLog can point at as its checkout
-- condition (UsageLog.CheckoutCondition is NOT NULL). Reuses an existing
-- resource from the normal seed just to satisfy the FK; it is not the
-- resource being logged.
INSERT INTO "ConditionLog" ("ResourceKey", "LoggedBy", "Condition", "Notes", "LoggedAt")
SELECT (SELECT "ResourceKey" FROM "ResourceInfo" LIMIT 1),
       (SELECT "AccountKey" FROM "AccountInfo" WHERE "UserID" = 'test_staff'),
       'Normal',
       'perf: bulk seed condition for NFR-PRF-05',
       now()
RETURNING "ConditionKey" \gset cond_

-- One ItemInfo type that owns all 10,000 bulk units, so the catalogue's
-- item.list has to page/sort/filter across a realistically large result set.
INSERT INTO "ItemInfo" ("ItemName", "ItemDesc", "CreditWeight")
VALUES ('Perf bulk stock (NFR-PRF-05)', 'Generated by perf/seed-large-dataset.sql - not real equipment', 1)
RETURNING "ItemKey" \gset item_

-- 10,000 lendable T0 units, owned by the first management group, and their
-- ItemIndiv rows in one data-modifying CTE.
WITH new_resources AS (
  INSERT INTO "ResourceInfo" ("ManagedBy", "BorrowRule", "ConditionKey", "ResourceStatus", "ResourceType", "BufferTime", "AllowBorrow")
  SELECT
    (SELECT MIN("ManageGroupKey") FROM "ManagementGroup"),
    (SELECT "BorrowRuleKey" FROM "BorrowRule" WHERE "RuleName" = 'T0'),
    :'cond_ConditionKey',
    'InStorage',
    'Item',
    0,
    true
  FROM generate_series(1, 10000)
  RETURNING "ResourceKey"
)
INSERT INTO "ItemIndiv" ("ResourceKey", "ItemKey", "ItemID")
SELECT "ResourceKey", :'item_ItemKey', 'PERF-' || "ResourceKey"
FROM new_resources;

-- 100,000 historical, completed loans (Reservations + matching UsageLog),
-- spread evenly (10 each) across the 10,000 bulk units, backdated so none of
-- them are "current" and none clash with a live load-test create/cancel.
WITH bulk_resources AS (
  SELECT ri."ResourceKey", (row_number() OVER (ORDER BY ri."ResourceKey") - 1) AS rn
  FROM "ResourceInfo" ri
  JOIN "ItemIndiv" ii ON ii."ResourceKey" = ri."ResourceKey"
  WHERE ii."ItemKey" = :'item_ItemKey'
),
gen AS (
  SELECT g,
         (g % 10000) AS rmod,
         now() - (g || ' hours')::interval AS start_t
  FROM generate_series(1, 100000) AS g
),
inserted_reservations AS (
  INSERT INTO "Reservations"
    ("ResourceKey", "ReservedBy", "StartTime", "EndTime", "ApproveStatus",
     "AutoApproved", "ApprovedAt", "ReservationExpiration", "ActionTime", "ResolvedAt")
  SELECT
    r."ResourceKey",
    (SELECT "AccountKey" FROM "AccountInfo" WHERE "UserID" = 'test_borrower'),
    gen.start_t,
    gen.start_t + interval '1 day',
    'Approved',
    true,
    gen.start_t,
    gen.start_t,
    gen.start_t,
    gen.start_t + interval '1 day'
  FROM gen
  JOIN bulk_resources r ON r.rn = gen.rmod
  RETURNING "ReservationKey", "ResourceKey", "StartTime"
)
INSERT INTO "UsageLog"
  ("ReservationKey", "AccountKey", "ResourceKey", "CurrentStatus", "DueTime",
   "CheckoutTime", "CheckInTime", "CheckoutCondition")
SELECT
  ir."ReservationKey",
  (SELECT "AccountKey" FROM "AccountInfo" WHERE "UserID" = 'test_borrower'),
  ir."ResourceKey",
  -- History that has been graded. 'Returned' means back but not yet
  -- inspected, which blocks the unit, so it would make every unit look busy.
  'Inspected',
  ir."StartTime" + interval '1 day',
  ir."StartTime",
  ir."StartTime" + interval '1 day',
  :'cond_ConditionKey'
FROM inserted_reservations ir;

COMMIT;

\echo 'NFR-PRF-05 bulk seed done:'
SELECT (SELECT count(*) FROM "ResourceInfo") AS total_resources,
       (SELECT count(*) FROM "Reservations") AS total_reservations,
       (SELECT count(*) FROM "UsageLog") AS total_usage_logs;
