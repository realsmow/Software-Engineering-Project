/**
 * Generates docs/api-reference.md from the tRPC routers.
 *
 * Generated rather than written by hand because a hand-maintained API doc is
 * wrong within a week, and a wrong doc is worse than none. Re-run it whenever a
 * procedure changes:
 *
 *   npm run docs:api
 *
 * It reads the decorators directly. If the count it finds ever disagrees with
 * `npm run trpc:generate`, one of them is out of date and the script says so
 * rather than emitting a quietly incomplete page.
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

const SRC = 'src';
const OUT = 'docs/api-reference.md';

/** Which middleware means which minimum role. */
const GUARDS = {
  AdminMiddleware: 'admin',
  SupervisorMiddleware: 'supervisor',
  StaffMiddleware: 'staff',
  AuthMiddleware: 'any signed-in user',
};

function routerFiles(dir) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === 'generated') continue;
      out.push(...routerFiles(path));
    } else if (entry.name.endsWith('.router.ts')) {
      out.push(path);
    }
  }
  return out;
}

function parseRouter(path) {
  const src = readFileSync(path, 'utf8');
  const alias = src.match(/@Router\(\{\s*alias:\s*'([^']+)'/)?.[1];
  if (!alias) return null;

  const procedures = [];
  // Walk line by line, holding the most recent guard and doc comment, because
  // decorators sit above the method they apply to.
  const lines = src.split('\n');
  let guard = null;
  let doc = null;

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];

    const guardMatch = line.match(/@UseMiddlewares\(([A-Za-z, ]+)\)/);
    if (guardMatch) {
      guard = guardMatch[1].split(',').map((g) => g.trim())[0];
      continue;
    }

    const docMatch = line.match(/^\s*\/\*\*\s*(.+?)\s*\*\/\s*$/);
    if (docMatch) {
      doc = docMatch[1];
      continue;
    }

    const kindMatch = line.match(/@(Query|Mutation)\(/);
    if (!kindMatch) continue;

    // The decorator may wrap across lines; collect until brackets balance.
    let block = line;
    let depth = (line.match(/\(/g) || []).length - (line.match(/\)/g) || []).length;
    let j = i;
    while (depth > 0 && j + 1 < lines.length) {
      j += 1;
      block += ' ' + lines[j].trim();
      depth += (lines[j].match(/\(/g) || []).length - (lines[j].match(/\)/g) || []).length;
    }

    const name = lines
      .slice(j + 1)
      .find((l) => /^\s+(async\s+)?[a-zA-Z]+\s*\(/.test(l))
      ?.match(/^\s+(?:async\s+)?([a-zA-Z]+)\s*\(/)?.[1];

    procedures.push({
      name: name ?? '(unknown)',
      kind: kindMatch[1].toLowerCase(),
      input: block.match(/input:\s*([A-Za-z0-9_]+)/)?.[1] ?? null,
      // Inline wrappers like `output: z.array(cronJobOutput)` would otherwise
      // report the schema as "z"; name what is inside the wrapper instead.
      output:
        block.match(/output:\s*z\.array\(([A-Za-z0-9_]+)\)/)?.[1]?.concat('[]') ??
        block.match(/output:\s*([A-Za-z0-9_]+)/)?.[1] ??
        null,
      access: guard ? (GUARDS[guard] ?? guard) : 'public',
      doc,
    });
    guard = null;
    doc = null;
  }

  return { alias, path, procedures };
}

const routers = routerFiles(SRC).map(parseRouter).filter(Boolean).sort((a, b) => a.alias.localeCompare(b.alias));
const total = routers.reduce((n, r) => n + r.procedures.length, 0);

const lines = [];
lines.push('# API reference');
lines.push('');
lines.push('> Generated by `npm run docs:api` from the router decorators.');
lines.push('> Do not edit by hand - re-run the script instead.');
lines.push('');
lines.push(`**${routers.length} routers, ${total} procedures.**`);
lines.push('');
lines.push('Transport is tRPC over HTTP at `/trpc`, not REST, so there is no OpenAPI');
lines.push('document: the contract is the TypeScript router type, checked at compile');
lines.push('time on both sides. This page is the human-readable view of it.');
lines.push('');
lines.push('Access is enforced by middleware on every procedure. `public` means no');
lines.push('session is required; everything else rejects an anonymous caller with');
lines.push('`NOT_AUTHENTICATED` and a wrong-role caller with `ROLE_NOT_ALLOWED`.');
lines.push('');

for (const r of routers) {
  lines.push(`## \`${r.alias}\``);
  lines.push('');
  lines.push(`Source: \`${r.path}\` · ${r.procedures.length} procedures`);
  lines.push('');
  lines.push('| Procedure | Type | Access | Input | Output |');
  lines.push('|---|---|---|---|---|');
  for (const p of r.procedures) {
    const cell = (v) => (v ? `\`${v}\`` : '-');
    lines.push(
      `| \`${r.alias}.${p.name}\` | ${p.kind} | ${p.access} | ${cell(p.input)} | ${cell(p.output)} |`,
    );
  }
  lines.push('');
  const documented = r.procedures.filter((p) => p.doc);
  if (documented.length) {
    lines.push('Notes:');
    lines.push('');
    for (const p of documented) lines.push(`- \`${p.name}\` - ${p.doc}`);
    lines.push('');
  }
}

mkdirSync('docs', { recursive: true });
writeFileSync(OUT, lines.join('\n') + '\n', 'utf8');
console.log(`wrote ${OUT}: ${routers.length} routers, ${total} procedures`);
